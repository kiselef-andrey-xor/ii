def q(t, text, opts, right, expl):
    """Проверка одного вопроса на месте: иначе ошибка уйдёт в прод."""
    assert isinstance(text, str) and len(text) > 9, text
    assert 2 <= len(opts) <= 5, (text, opts)
    assert 0 <= right < len(opts), (text, right)
    assert isinstance(expl, str) and len(expl) > 15, (text, expl)
    return {'t': t, 'q': text, 'o': list(opts), 'a': int(right), 'e': expl}


